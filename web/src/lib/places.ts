/** "Sweden" → "SE", "se" → "SE", "California" → "US-CA"; unknown words come back as typed (the server says no). */
export function placeCode(v: string): string {
  const s = v.trim().replace(/\s+/g, " ");
  const up = s.toUpperCase();
  if (up in PLACE_NAMES) return up;
  if (s.toLowerCase() === "global") return "global";
  return NAME_TO_CODE[s.toLowerCase()] ?? s;
}

export const placeName = (code: string) => PLACE_NAMES[code] ?? code;
export const topicWord = (t: string) =>
  t === "intellectual-property" ? "IP" : t.charAt(0).toUpperCase() + t.slice(1).replace("-", " ");
